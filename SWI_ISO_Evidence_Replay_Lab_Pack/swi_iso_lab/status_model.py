"""Authoritative status model — single vocabulary for evidence, replay, docs."""
from __future__ import annotations
from enum import Enum

class Outcome(str, Enum):
    PASS = "PASS"
    FAIL = "FAIL"
    NOT_RUN = "NOT_RUN"
    NOT_ASSESSED = "NOT_ASSESSED"
    PARTIAL = "PARTIAL"
    REJECT = "REJECT"

class Scope(str, Enum):
    PACKAGE_STRUCTURE = "PACKAGE_STRUCTURE"
    SCHEMA_VALIDATION = "SCHEMA_VALIDATION"
    LEDGER_INTEGRITY = "LEDGER_INTEGRITY"
    SWI_KERNEL_TEST = "SWI_KERNEL_TEST"
    ISO_CLAUSE_COMPATIBILITY = "ISO_CLAUSE_COMPATIBILITY"
    CRYPTOGRAPHIC_VERIFICATION = "CRYPTOGRAPHIC_VERIFICATION"

class ReplayStatus(str, Enum):
    NOT_RUN = "NOT_RUN"
    REPLAY_MATCH = "REPLAY_MATCH"
    MISMATCH = "MISMATCH"
    INCOMPLETE = "INCOMPLETE"
    SOURCE_UNAVAILABLE = "SOURCE_UNAVAILABLE"
    ENVIRONMENT_DRIFT = "ENVIRONMENT_DRIFT"
    NOT_REPRODUCIBLE = "NOT_REPRODUCIBLE"

class LedgerMark(str, Enum):
    ACTIVE = "ACTIVE"
    HISTORICAL_DUPLICATE = "HISTORICAL_DUPLICATE"
    NOT_VALID_FOR_NEW_ADMISSION = "NOT_VALID_FOR_NEW_ADMISSION"
    SUPERSEDED = "SUPERSEDED"

GOVERNANCE_DEFAULTS = {
    "PROVEN": False,
    "SEALED": False,
    "AUTHORIZED": False,
    "PRODUCTION_AUTHORIZED": False,
}
